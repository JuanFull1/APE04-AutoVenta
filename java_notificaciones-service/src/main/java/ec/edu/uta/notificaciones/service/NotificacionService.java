
package ec.edu.uta.notificaciones.service;

import com.fasterxml.jackson.databind.JsonNode;
import ec.edu.uta.notificaciones.dto.NotificacionDetalle;
import ec.edu.uta.notificaciones.dto.NotificacionRequest;
import ec.edu.uta.notificaciones.dto.NotificacionResponse;

import jakarta.annotation.PostConstruct;

import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.UUID;

@Service
public class NotificacionService {

    private static final Set<String> TIPOS_PERMITIDOS =
            Set.of(
                    "REGISTRO",
                    "ACTUALIZACION",
                    "ELIMINACION",
                    "VENTA"
            );

    private final JdbcTemplate jdbc;

    public NotificacionService(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    // =====================================================
    // CREAR ESTRUCTURA PERSISTENTE
    // =====================================================

    @PostConstruct
    public void inicializarTabla() {

        jdbc.execute("""
            CREATE TABLE IF NOT EXISTS notificaciones (
                id BIGINT GENERATED BY DEFAULT
                    AS IDENTITY PRIMARY KEY,

                evento_id VARCHAR(100)
                    NOT NULL UNIQUE,

                venta_id BIGINT,

                vehiculo_id INTEGER NOT NULL,

                comprador_id INTEGER,

                tipo VARCHAR(30) NOT NULL,

                destinatario VARCHAR(200),

                mensaje VARCHAR(500) NOT NULL,

                fecha_evento_utc VARCHAR(40),

                fecha_recepcion_utc VARCHAR(40)
                    NOT NULL
            )
            """);
    }

    // =====================================================
    // GUARDAR EVENTO PROCEDENTE DE RABBITMQ
    // =====================================================

    @Transactional
    public boolean registrarEvento(JsonNode evento) {

        if (evento == null || !evento.isObject()) {
            throw new IllegalArgumentException(
                    "El evento debe ser un objeto JSON"
            );
        }

        String nombreEvento = texto(
                evento,
                "evento"
        );

        if (!"VENTA_REALIZADA".equals(nombreEvento)) {
            throw new IllegalArgumentException(
                    "Tipo de evento no permitido"
            );
        }

        String estadoVenta = texto(
                evento,
                "estado"
        );

        if (!"COMPLETADA".equals(estadoVenta)) {
            throw new IllegalArgumentException(
                    "Solo se notifican ventas completadas"
            );
        }

        String eventoId = texto(
                evento,
                "eventoId"
        );

        long ventaId = evento.path("ventaId")
                .asLong(0);

        int vehiculoId = evento.path("vehiculoId")
                .asInt(0);

        int compradorId = evento.path("compradorId")
                .asInt(0);

        if (eventoId.isBlank()
                || ventaId <= 0
                || vehiculoId <= 0) {

            throw new IllegalArgumentException(
                    "Evento sin identificadores válidos"
            );
        }

        // Protege contra la repetición del mismo evento.
        if (existe(eventoId)) {
            return false;
        }

        String destinatario = texto(
                evento,
                "destinatario"
        );

        String mensaje = texto(
                evento,
                "mensaje"
        );

        if (mensaje.isBlank()) {
            mensaje = "Venta " + ventaId
                    + " completada correctamente";
        }

        String fechaEvento = texto(
                evento,
                "fechaUTC"
        );

        String fechaRecepcion =
                OffsetDateTime.now(ZoneOffset.UTC)
                        .toString();

        try {
            jdbc.update("""
                INSERT INTO notificaciones (
                    evento_id,
                    venta_id,
                    vehiculo_id,
                    comprador_id,
                    tipo,
                    destinatario,
                    mensaje,
                    fecha_evento_utc,
                    fecha_recepcion_utc
                )
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                    eventoId,
                    ventaId,
                    vehiculoId,
                    compradorId > 0 ? compradorId : null,
                    "VENTA",
                    destinatario,
                    mensaje,
                    fechaEvento,
                    fechaRecepcion
            );

            return true;

        } catch (DuplicateKeyException duplicado) {
            // La restricción UNIQUE también protege
            // frente a dos inserciones simultáneas.
            return false;
        }
    }

    // =====================================================
    // MANTENER EL ENDPOINT HTTP ORIGINAL
    // =====================================================

    @Transactional
    public NotificacionResponse procesar(
            NotificacionRequest request) {

        if (request == null) {
            throw new IllegalArgumentException(
                    "La solicitud no puede estar vacía"
            );
        }

        if (request.getVehiculoId() == null
                || request.getVehiculoId() <= 0) {

            throw new IllegalArgumentException(
                    "vehiculoId debe ser válido"
            );
        }

        if (request.getDestinatario() == null
                || request.getDestinatario().isBlank()) {

            throw new IllegalArgumentException(
                    "El destinatario no puede estar vacío"
            );
        }

        if (request.getMensaje() == null
                || request.getMensaje().isBlank()) {

            throw new IllegalArgumentException(
                    "El mensaje no puede estar vacío"
            );
        }

        String tipo = request.getTipo() == null
                ? ""
                : request.getTipo()
                    .trim()
                    .toUpperCase(Locale.ROOT);

        if (!TIPOS_PERMITIDOS.contains(tipo)) {
            throw new IllegalArgumentException(
                    "Tipo de notificación no válido"
            );
        }

        String fecha =
                OffsetDateTime.now(ZoneOffset.UTC)
                        .toString();

        jdbc.update("""
            INSERT INTO notificaciones (
                evento_id,
                venta_id,
                vehiculo_id,
                comprador_id,
                tipo,
                destinatario,
                mensaje,
                fecha_evento_utc,
                fecha_recepcion_utc
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
                UUID.randomUUID().toString(),
                null,
                request.getVehiculoId(),
                null,
                tipo,
                request.getDestinatario(),
                request.getMensaje(),
                null,
                fecha
        );

        System.out.println(
                "[HTTP] Notificación registrada. Vehículo #"
                        + request.getVehiculoId()
        );

        return new NotificacionResponse(
                true,
                "ENVIADA",
                "Notificación procesada correctamente"
        );
    }

    // =====================================================
    // CONSULTAR NOTIFICACIONES
    // =====================================================

    @Transactional(readOnly = true)
    public List<NotificacionDetalle> listar() {

        return jdbc.query("""
            SELECT
                id,
                evento_id,
                venta_id,
                vehiculo_id,
                comprador_id,
                tipo,
                destinatario,
                mensaje,
                fecha_evento_utc,
                fecha_recepcion_utc
            FROM notificaciones
            ORDER BY id DESC
            """,
                (rs, fila) -> new NotificacionDetalle(
                        rs.getLong("id"),
                        rs.getString("evento_id"),
                        rs.getObject(
                                "venta_id",
                                Long.class
                        ),
                        rs.getInt("vehiculo_id"),
                        rs.getObject(
                                "comprador_id",
                                Integer.class
                        ),
                        rs.getString("tipo"),
                        rs.getString("destinatario"),
                        rs.getString("mensaje"),
                        rs.getString("fecha_evento_utc"),
                        rs.getString("fecha_recepcion_utc")
                )
        );
    }

    @Transactional(readOnly = true)
    public long total() {

        Long cantidad = jdbc.queryForObject(
                "SELECT COUNT(*) FROM notificaciones",
                Long.class
        );

        return cantidad == null ? 0 : cantidad;
    }

    // =====================================================
    // MÉTODOS INTERNOS
    // =====================================================

    private boolean existe(String eventoId) {

        Integer cantidad = jdbc.queryForObject(
                """
                SELECT COUNT(*)
                FROM notificaciones
                WHERE evento_id = ?
                """,
                Integer.class,
                eventoId
        );

        return cantidad != null && cantidad > 0;
    }

    private String texto(
            JsonNode evento,
            String campo) {

        JsonNode valor = evento.path(campo);

        if (valor.isMissingNode() || valor.isNull()) {
            return "";
        }

        return valor.asText("").trim();
    }
}
